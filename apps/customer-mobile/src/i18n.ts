const CATEGORY_KEYS: Record<ProductCategory, Key> = {
  BOUQUET: 'categoryBouquet',
  ROSES: 'categoryRoses',
  PLANTS: 'categoryPlants',
  ARRANGEMENT: 'categoryArrangement',
  WEDDING: 'categoryWedding',
  FUNERAL: 'categoryFuneral',
  GIFT: 'categoryGift',
  OTHER: 'categoryOther',
};

const label = (keys: Record<string, Key>, value: string): string => {
  const key = keys[value];
  return key ? t(key) : value;
};

/** Order (and delivery) status shown to the customer. */
export const orderStatusLabel = (status: string): string => label(STATUS_KEYS, status);
export const requestStatusLabel = (status: string): string => label(REQUEST_KEYS, status);
export const offerStatusLabel = (status: string): string => label(OFFER_KEYS, status);
export const categoryLabel = (category: ProductCategory): string => t(CATEGORY_KEYS[category]);
